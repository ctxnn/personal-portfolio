#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const login = process.argv[2] || 'ctxnn';
const query = `
  query($login: String!) {
    user(login: $login) {
      contributionsCollection {
        contributionCalendar {
          totalContributions
          weeks {
            contributionDays {
              date
              contributionCount
            }
          }
        }
      }
    }
  }
`;

const response = execFileSync(
  'gh',
  ['api', 'graphql', '-f', `query=${query}`, '-F', `login=${login}`],
  { encoding: 'utf8', maxBuffer: 1024 * 1024 }
);

const calendar = JSON.parse(response)?.data?.user?.contributionsCollection?.contributionCalendar;
if (!calendar?.weeks?.length) {
  throw new Error(`GitHub returned no contribution calendar for ${login}.`);
}

const days = calendar.weeks.flatMap(({ contributionDays }) =>
  contributionDays.map(({ date, contributionCount }) => ({
    date,
    count: Number(contributionCount) || 0
  }))
);

const snapshotData = {
  login,
  totalContributions: Number(calendar.totalContributions) || 0,
  days
};

const destination = fileURLToPath(new URL('../github-activity.js', import.meta.url));
if (existsSync(destination)) {
  const existingSource = readFileSync(destination, 'utf8');
  const payloadStart = existingSource.indexOf('{');
  const payloadEnd = existingSource.lastIndexOf(';');

  if (payloadStart !== -1 && payloadEnd > payloadStart) {
    const existing = JSON.parse(existingSource.slice(payloadStart, payloadEnd));
    const existingData = {
      login: existing.login,
      totalContributions: existing.totalContributions,
      days: existing.days
    };

    if (JSON.stringify(existingData) === JSON.stringify(snapshotData)) {
      console.log(`Activity snapshot for ${login} is already current.`);
      process.exit(0);
    }
  }
}

const snapshot = {
  ...snapshotData,
  updatedAt: new Date().toISOString()
};

writeFileSync(
  destination,
  `// Generated by scripts/update-github-activity.mjs.\nwindow.__GITHUB_ACTIVITY__ = ${JSON.stringify(snapshot, null, 2)};\n`
);
console.log(`Updated ${days.length} activity days for ${login}.`);
